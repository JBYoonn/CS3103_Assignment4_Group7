"""Per-client overload detection and message-rate control.

Why this exists
---------------
On a WebSocket the server cannot see when the *application* at the other end
has actually read a message. Data handed to TCP is buffered in our send buffer,
on the path, in the client's kernel receive buffer, and in the client
library's own message queue. A slow reader therefore looks perfectly healthy
to `ws.send()` until all of those buffers are full -- by which time the
client is many seconds behind. "Queue everything" just turns those buffers
into a growing backlog of stale revisions.

The signal we use: WebSocket ping/pong. A pong is generated by the client's
WebSocket stack only after it has read every byte sent before the ping, so

    lag = (time until pong) - (smallest RTT ever seen on this connection)

is the queueing delay between us and the client's reader. Subtracting the
minimum RTT means a long-but-healthy path (e.g. netem delay) is not mistaken
for overload.

Caveat that shapes the policy: the Python `websockets` client keeps reading
from TCP until ~16 messages are waiting in its own queue, and answers pings
while it reads. So lag only becomes visible once a client is already ~16
messages behind, and any time we send faster than a slow reader can consume
it costs that hidden backlog again.

The policy (multiplicative decrease, held probes -- TCP-congestion-control style)
---------------------------------------------------------------------------------
  NORMAL      no limit; every revision is sent (keeps Normal Update Coverage).
  cut         lag > lag_high -> LIMITED. First cut: rate = sent_rate / 4.
  gate        while the outstanding ping is overdue the client is visibly
              backlogged: send nothing. Pending finals keep accumulating in
              the outbox and later go out as ONE batch, so the client drains
              at its full speed instead of (its speed - our rate).
  hold        the first timely pong after a cut ends the episode. The rate is
              then held flat for about as long as the episode lasted (between
              min_hold_s and plateau_s): a brief network hiccup recovers in
              seconds, a genuinely slow reader is probed rarely.
  step up     a hold that completes with timely pongs proves the rate; the
              next hold tries rate * step (small, because an overshoot stays
              invisible until the client is ~16 messages behind).
  failed      lag during a step-up hold: fall back to the last proven rate and
  probe       double plateau_s (exponential backoff, capped at max_plateau_s).
  worse       lag at an already-proven rate: halve it.
  exit        once the allowed rate exceeds exit_factor * the source's offered
              rate it no longer binds: back to NORMAL.

Each cut only counts pings sent after the previous cut, so one backlog episode
is not punished repeatedly.
"""

from __future__ import annotations

import math
from collections import deque


class FlowController:
    def __init__(
        self,
        lag_high: float = 0.5,
        lag_low: float = 0.15,
        min_rate: float = 0.5,
        step: float = 1.25,
        min_hold_s: float = 2.0,
        plateau_s: float = 10.0,
        max_plateau_s: float = 80.0,
        exit_factor: float = 1.5,
        burst: float = 2.0,
        rate_window_s: float = 2.0,
    ):
        self.lag_high = lag_high
        self.lag_low = lag_low
        self.min_rate = min_rate
        self.step = step
        self.min_hold_s = min_hold_s
        self.base_plateau_s = plateau_s
        self.plateau_s = plateau_s          # longest hold; doubles after failed probes
        self.max_plateau_s = max_plateau_s
        self.exit_factor = exit_factor
        self.burst = burst
        self.rate_window_s = rate_window_s

        self.limited = False
        self.rate = math.inf          # allowed messages/s while limited
        self.held_rate = math.inf     # last rate proven by a completed hold
        self.tokens = burst
        self.min_rtt = math.inf
        self.cut_at = -math.inf       # only pings sent after this can trigger another cut
        self.recovering = False       # cut made, no timely pong yet
        self.hold_len = min_hold_s
        self.hold_until = math.inf
        self._last_refill = 0.0
        self._sends: deque[float] = deque()
        self.cuts = 0                 # for logs / the report

    # -- measurements ------------------------------------------------------

    def lag(self, rtt: float) -> float:
        base = self.min_rtt if self.min_rtt != math.inf else 0.0
        return max(0.0, rtt - base)

    def sent_rate(self, now: float) -> float:
        while self._sends and self._sends[0] < now - self.rate_window_s:
            self._sends.popleft()
        return len(self._sends) / self.rate_window_s

    def on_sent(self, now: float) -> None:
        self._sends.append(now)
        if self.limited:
            self._refill(now)
            self.tokens -= 1.0

    def on_ping_age(self, now: float, sent_at: float) -> None:
        """Called periodically while a ping is outstanding."""
        lag = self.lag(now - sent_at)
        if lag > self.lag_high and sent_at > self.cut_at:
            self._cut(now)

    def on_pong(self, now: float, sent_at: float, offered_rate: float) -> None:
        rtt = now - sent_at
        lag = self.lag(rtt)
        self.min_rtt = min(self.min_rtt, rtt)
        if lag > self.lag_high:
            if sent_at > self.cut_at:
                self._cut(now)
            return
        if self.limited and lag < self.lag_low and sent_at > self.cut_at:
            self._timely(now, offered_rate)

    # -- policy --------------------------------------------------------------

    def _cut(self, now: float) -> None:
        if not self.limited:
            self.limited = True
            self.rate = self.held_rate = max(self.min_rate, 0.25 * self.sent_rate(now))
            self.tokens = min(self.tokens, 1.0)
            self._last_refill = now
        elif self.rate > self.held_rate:                         # a step-up probe failed
            self.plateau_s = min(self.max_plateau_s, 2.0 * self.plateau_s)
            self.rate = self.held_rate
        else:                                                    # proven rate no longer works
            self.rate = self.held_rate = max(self.min_rate, 0.5 * self.rate)
        self.cut_at = now
        self.recovering = True
        self.hold_until = math.inf
        self.cuts += 1

    def _timely(self, now: float, offered_rate: float) -> None:
        if self.recovering:                                      # episode over: start the hold
            self.recovering = False
            self.hold_len = min(self.plateau_s, max(self.min_hold_s, now - self.cut_at))
            self.hold_until = now + self.hold_len
            return
        if now < self.hold_until:
            return
        self.held_rate = self.rate                               # survived a full hold
        self.rate *= self.step
        self.hold_until = now + self.hold_len
        if offered_rate > 0 and self.rate >= self.exit_factor * offered_rate:
            self.limited = False
            self.rate = self.held_rate = math.inf
            self.plateau_s = self.base_plateau_s
            self.hold_until = math.inf
            self.tokens = self.burst

    # -- pacing --------------------------------------------------------------

    def gated(self, now: float, ping_sent_at: float | None) -> bool:
        """True while the client is visibly backlogged: send nothing now."""
        return (self.limited and ping_sent_at is not None
                and self.lag(now - ping_sent_at) > self.lag_high)

    def _refill(self, now: float) -> None:
        if now > self._last_refill:
            self.tokens = min(self.burst, self.tokens + self.rate * (now - self._last_refill))
            self._last_refill = now

    def ready_in(self, now: float) -> float:
        """Seconds until the next message may be sent (0 = now)."""
        if not self.limited:
            return 0.0
        self._refill(now)
        if self.tokens >= 1.0:
            return 0.0
        return (1.0 - self.tokens) / self.rate
